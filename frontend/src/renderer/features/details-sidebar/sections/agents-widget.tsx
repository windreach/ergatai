// Backend auto-spawns runtime agents named like "ws_5019..._agent-12".
// Detect those so we can show the registered profile name instead.
function looksAutoGenerated(name: string, agentId: string): boolean {
  return name === agentId || /^ws[_-]/.test(name)
}

// Resolve the display name. The backend often renames runtime agent instances
// (auto ids like "ws_..._agent-12" or even the session title), so whenever the
// runtime carries a `profile`, resolve from the registered profiles table
// (agent 配置表) or the canonical core agent id instead of trusting `name`.
function resolveDisplayName(
  participant: {
    name: string
    agentId: string
    coreAgentId?: CoreAgentId
    profile?: string | null
  },
  profiles: { name: string; command: string }[],
): string {
  const profileId = participant.profile?.trim().toLowerCase()
  if (profileId) {
    const exact = profiles.find(
      (profile) => profile.name.trim().toLowerCase() === profileId,
    )
    // Registry profiles seeded from core agent ids carry the raw id as their
    // name (e.g. "opencode") — show the canonical display name instead so
    // ad-hoc runtime agents don't show up as raw id labels in the list.
    if (exact) return getCoreAgentDisplayName(exact.name) ?? exact.name
    const byCommand = profiles.find((profile) =>
      profile.command.toLowerCase().includes(profileId),
    )
    if (byCommand) return byCommand.name
    if (participant.coreAgentId) {
      return (
        getCoreAgentDisplayName(participant.coreAgentId) ??
        participant.coreAgentId
      )
    }
    return participant.profile!.trim()
  }
  if (looksAutoGenerated(participant.name, participant.agentId)) {
    return (
      getCoreAgentDisplayName(participant.coreAgentId) ??
      participant.coreAgentId ??
      participant.name
    )
  }
  return participant.name
}

interface AgentsWidgetProps {
  chatId: string
}

const STATUS_DOT_CLASS: Record<string, string> = {
  running: "bg-emerald-500",
  pending: "bg-amber-500",
  failed: "bg-rose-500",
  completed: "bg-muted-foreground/40",
  idle: "bg-muted-foreground/30",
}

/**
 * Agents participating in the current chat (same data source the main
 * page agent rail used: group members in group mode, runtime agents
 * filtered by chat bindings otherwise). Live status, refreshes every 5s.
 * Clicking an agent opens its side chat in the independent side chat
 * sidebar (coexists with the Details sidebar).
 */
export const AgentsWidget = memo(function AgentsWidget({ chatId }: AgentsWidgetProps) {
  const participants = useAgentParticipants({
    chatId,
    workspaceId: null,
    runtimeWorkspaceId: null,
    supervisorAgentId: null,
  })
  const { data: profilesData } = trpc.ergatai.listProfiles.useQuery()
  const profiles = profilesData?.profiles ?? []
  const setIsSideChatSidebarOpen = useSetAtom(sideChatSidebarOpenAtom)
  const setAgentChatRequest = useSetAtom(
    groupAgentChatRequestAtomFamily(chatId),
  )

  const openAgentChat = (
    agentId: string,
    coreAgentId: CoreAgentId | undefined,
    conversationId: string | undefined,
  ) => {
    if (!conversationId) return
    setIsSideChatSidebarOpen(true)
    setAgentChatRequest({
      agentId: coreAgentId ?? (agentId as CoreAgentId),
      conversationId,
      requestId: Date.now(),
    })
  }

  return (
    <WidgetCard widgetId="agents" title="Agents">
      <div className="px-1.5 py-1.5">
        {participants.length > 0 &&
          participants.map((participant) => {
            const Icon = getCoreAgentIcon(
              (participant.coreAgentId ?? participant.agentId) as CoreAgentId,
            )
            const clickable = Boolean(participant.conversationId)
            const displayName = resolveDisplayName(participant, profiles)
            return (
              <button
                key={participant.key}
                type="button"
                disabled={!clickable}
                onClick={() =>
                  openAgentChat(
                    participant.agentId,
                    participant.coreAgentId,
                    participant.conversationId,
                  )
                }
                className={cn(
                  "flex w-full items-center gap-2 rounded-md px-1 py-1.5 text-left transition-colors",
                  clickable ? "hover:bg-muted/50" : "cursor-default",
                )}
                title={participant.activity || undefined}
              >
                <div className="flex h-5 w-5 flex-shrink-0 items-center justify-center rounded-md bg-muted">
                  <Icon className="h-3 w-3 text-muted-foreground" />
                </div>
                <div className="min-w-0 flex-1">
                  <div className="truncate text-xs font-medium text-foreground">
                    {displayName}
                  </div>
                  {participant.activity && (
                    <div className="truncate text-[10px] text-muted-foreground/60">
                      {participant.activity}
                    </div>
                  )}
                </div>
                <span
                  className={cn(
                    "h-1.5 w-1.5 flex-shrink-0 rounded-full",
                    STATUS_DOT_CLASS[participant.status] ??
                      "bg-muted-foreground/30",
                  )}
                />
              </button>
            )
          })}
      </div>
    </WidgetCard>
  )
})
