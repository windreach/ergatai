// Backend auto-spawns runtime agents named like "ws_5019..._agent-12".
// Detect those so we can show the registered profile name instead.
function looksAutoGenerated(name: string, agentId: string): boolean {
  return name === agentId || /^ws[_-]/.test(name) || /^agent[_-]/.test(name)
}

function looksLikeAgentId(value: string): boolean {
  return /^agent[_-]/i.test(value) || /^ws[_-]/i.test(value) || /^conv[_-]/i.test(value)
}

// Resolve the display name. The backend often renames runtime agent instances
// (auto ids like "ws_..._agent-12" or even the session title), so whenever the
// runtime carries a `profile`, resolve from the registered profiles table
// (agent 配置表) or the canonical core agent id instead of trusting `name`.
function resolveDisplayName(
  participant: {
    name: string
    agentId: string
    coreAgentId?: CoreAgentId
    profile?: string | null
  },
  profiles: { name: string; command: string }[],
): string {
  const profileId = participant.profile?.trim().toLowerCase()
  if (profileId) {
    const exact = profiles.find(
      (profile) => profile.name.trim().toLowerCase() === profileId,
    )
    // Registry profiles seeded from core agent ids carry the raw id as their
    // name (e.g. "opencode") — show the canonical display name instead so
    // ad-hoc runtime agents don't show up as raw id labels in the list.
    if (exact) return getCoreAgentDisplayName(exact.name) ?? exact.name
    const byCommand = profiles.find((profile) =>
      profile.command.toLowerCase().includes(profileId),
    )
    if (byCommand) return byCommand.name
    if (participant.coreAgentId) {
      return (
        getCoreAgentDisplayName(participant.coreAgentId) ??
        participant.coreAgentId
      )
    }
    return looksLikeAgentId(participant.profile!.trim())
      ? "Agent"
      : participant.profile!.trim()
  }
  if (looksAutoGenerated(participant.name, participant.agentId)) {
    return (
      getCoreAgentDisplayName(participant.coreAgentId) ??
      participant.coreAgentId ??
      (looksLikeAgentId(participant.name) ? "Agent" : participant.name)
    )
  }
  if (looksLikeAgentId(participant.name)) {
    console.error("Unable to resolve agent display name", participant)
    return "Agent"
  }
  return participant.name
}

interface AgentsWidgetProps {
  chatId: string
  activeConversationId?: string | null
}

const STATUS_DOT_CLASS: Record<string, string> = {
  running: "bg-emerald-500",
  pending: "bg-amber-500",
  failed: "bg-rose-500",
  completed: "bg-muted-foreground/40",
  idle: "bg-muted-foreground/30",
}

/**
 * Agents participating in the current chat (same data source the main
 * page agent rail used: group members in group mode, runtime agents
 * filtered by chat bindings otherwise). Live status, refreshes every 5s.
 * Clicking an agent opens its side chat in the independent side chat
 * sidebar (coexists with the Details sidebar).
 */
export const AgentsWidget = memo(function AgentsWidget({ chatId, activeConversationId }: AgentsWidgetProps) {
  const participants = useAgentParticipants({
    chatId,
    workspaceId: null,
    runtimeWorkspaceId: null,
    supervisorAgentId: null,
  })
  const { data: profilesData } = trpc.ergatai.listProfiles.useQuery()
  const profiles = profilesData?.profiles ?? []
  const bindingsQuery = trpc.ergatai.getAgentBindings.useQuery(
    { chatId },
    { enabled: chatId.startsWith("chat_") },
  )
  const utils = trpc.useUtils()
  const spawnMutation = trpc.ergatai.spawnAgent.useMutation()
  const deleteAgentMutation = trpc.ergatai.deleteChatAgent.useMutation()
  const existingAgentIds = new Set([
    ...participants.flatMap((p) => [
      p.coreAgentId,
      p.profile,
      p.agentId,
    ].filter(Boolean)),
    ...(bindingsQuery.data ?? []).flatMap((b) => [
      b.agentCommand,
      b.agentName,
    ].filter(Boolean)),
  ])
  const [coreAgents, setCoreAgents] = useState<CoreAgentOption[]>([])
  const [chatAgentsLoaded, setChatAgentsLoaded] = useState(false)
  const [hiddenAgentIds, setHiddenAgentIds] = useState<Set<string>>(new Set())
  useEffect(() => {
    if (chatAgentsLoaded) return
    let cancelled = false
    agentContractApi
      .listCoreAgents()
      .then((agents) => {
        if (cancelled) return
        setCoreAgents(agents)
        setChatAgentsLoaded(true)
      })
      .catch((error) => {
        if (cancelled) return
        console.error("Failed to load core agents", error)
        setChatAgentsLoaded(true)
      })
    return () => {
      cancelled = true
    }
  }, [chatAgentsLoaded])
  const availableAgents = coreAgents.filter((agent) => {
    const keys = [agent.id, agent.profileName, agent.name].filter(Boolean)
    return !keys.some((key) => existingAgentIds.has(key as string))
  })
  const visibleParticipants = participants.filter(
    (participant) =>
      !hiddenAgentIds.has(participant.key) &&
      !hiddenAgentIds.has(participant.agentId),
  )
  const setIsSideChatSidebarOpen = useSetAtom(sideChatSidebarOpenAtom)
  const setIsDetailsSidebarOpen = useSetAtom(detailsSidebarOpenAtom)
  const setAgentChatRequest = useSetAtom(
    groupAgentChatRequestAtomFamily(chatId),
  )

  const openAgentChat = (
    agentId: string,
    coreAgentId: CoreAgentId | undefined,
    conversationId: string | undefined,
  ) => {
    if (!conversationId) return
    setIsDetailsSidebarOpen(false)
    setIsSideChatSidebarOpen(true)
    setAgentChatRequest({
      agentId: coreAgentId ?? (agentId as CoreAgentId),
      conversationId,
      requestId: Date.now(),
    })
  }

  const handleSelectAgent = async (agent: CoreAgentOption) => {
    try {
      const conversation = await trpcClient.ergatai.createConversation.mutate({
        chatId,
        title: agent.name,
        mode: "agent",
      })
      const newConversationId = conversation.id
      const spawnResult = await spawnMutation.mutateAsync({
        conversationId: newConversationId,
        command: agent.profileName || agent.id,
      })
      const spawnedAgentId = spawnResult?.agent_id
      if (spawnedAgentId) {
        await trpcClient.ergatai.promptAgent.mutate({
          agentId: spawnedAgentId,
          message: `Hello`,
          conversationId: newConversationId,
          waitForStream: false,
        })
      }
      await utils.ergatai.getAgentBindings.invalidate({ chatId })
      const result = await bindingsQuery.refetch()
      const binding = result.data?.find(
        (item) => item.agentId === spawnedAgentId || item.agentId === agent.id,
      )
      setIsDetailsSidebarOpen(false)
      setIsSideChatSidebarOpen(true)
      setAgentChatRequest({
        agentId: agent.id,
        conversationId: binding?.conversationId ?? newConversationId,
        requestId: Date.now(),
      })
    } catch (error) {
      console.error("Failed to start agent", error)
      toast.error("Failed to start agent", {
        description: error instanceof Error ? error.message : String(error),
      })
    }
  }

  const handleCloseAgent = async (
    participant: { source: string; agentId: string; key: string },
  ) => {
    // Group members are UI-side group participants, not durable runtime
    // bindings. The permanent deletion API is for chat-scoped runtime agents.
    if (participant.source !== "runtime" && participant.source !== "stopped") {
      return
    }

    try {
      // The backend stops live runtime agents and permanently removes the
      // binding and conversation; message tables are queued for async cleanup.
      await deleteAgentMutation.mutateAsync({
        chatId,
        agentId: participant.agentId,
      })

      setHiddenAgentIds((previous) => {
        const next = new Set(previous)
        next.add(participant.key)
        next.add(participant.agentId)
        return next
      })

      await utils.ergatai.getAgentBindings.invalidate({ chatId })
      await bindingsQuery.refetch()
    } catch (error) {
      console.error("Failed to permanently delete agent", error)
      toast.error("Failed to delete agent", {
        description: error instanceof Error ? error.message : String(error),
      })
    }
  }

  return (
    <WidgetCard widgetId="agents" title="Agents">
      <div className="px-1.5 py-1.5">
        <DropdownMenu>
          <DropdownMenuTrigger asChild>
            <Button
              variant="outline"
              size="sm"
              aria-label="New agent"
              className="h-7 w-full justify-center gap-1.5 rounded-lg text-sm font-medium"
            >
              <Plus className="h-3.5 w-3.5" />
              <span>New agent</span>
            </Button>
          </DropdownMenuTrigger>
          <DropdownMenuContent align="start" className="w-56">
            {availableAgents.length === 0 ? (
              <div className="px-2 py-1.5 text-xs text-muted-foreground">
                No agents available
              </div>
            ) : (
              availableAgents.map((agent) => {
                const Icon = getCoreAgentIcon(agent.id as any)
                return (
                  <DropdownMenuItem
                    key={agent.id}
                    onSelect={() => handleSelectAgent(agent)}
                    className="flex items-center gap-2 text-xs"
                  >
                    <Icon className="h-3.5 w-3.5 flex-shrink-0 text-muted-foreground" />
                    <span className="min-w-0 truncate">{agent.name}</span>
                  </DropdownMenuItem>
                )
              })
            )}
          </DropdownMenuContent>
        </DropdownMenu>
      </div>
      <div className="px-1.5 py-1.5">
        {visibleParticipants.length > 0 &&
          visibleParticipants.map((participant) => {
            const Icon = getCoreAgentIcon(
              (participant.coreAgentId ?? participant.agentId) as CoreAgentId,
            )
            const clickable = Boolean(participant.conversationId)
            const displayName = resolveDisplayName(participant, profiles)
            return (
              <button
                key={participant.key}
                type="button"
                disabled={!clickable}
                onClick={() =>
                  openAgentChat(
                    participant.agentId,
                    participant.coreAgentId,
                    participant.conversationId,
                  )
                }
                className={cn(
                  "group flex w-full items-center gap-2 rounded-md px-1 py-1.5 text-left transition-colors",
                  clickable ? "hover:bg-muted/50" : "cursor-default",
                )}
                title={participant.activity || undefined}
              >
                <div className="flex h-5 w-5 flex-shrink-0 items-center justify-center rounded-md bg-muted">
                  <Icon className="h-3 w-3 text-muted-foreground" />
                </div>
                <div className="min-w-0 flex-1">
                  <div className="truncate text-xs font-medium text-foreground">
                    {displayName}
                  </div>
                  {participant.activity && (
                    <div className="truncate text-[10px] text-muted-foreground/60">
                      {participant.activity}
                    </div>
                  )}
                </div>
                <span className="relative flex h-4 w-4 flex-shrink-0 items-center justify-center">
                  <span
                    className={cn(
                      "h-1.5 w-1.5 rounded-full transition-opacity group-hover:opacity-0",
                      STATUS_DOT_CLASS[participant.status] ??
                        "bg-muted-foreground/30",
                    )}
                  />
	                  {/* react-doctor-disable-next-line html-no-nested-interactive */}
	                  <button
	                    type="button"
	                    aria-label="Permanently delete agent"
	                    title="Permanently delete agent and its conversation"
                    onClick={(event) => {
                      event.stopPropagation()
                      void handleCloseAgent(participant)
                    }}
                    className="absolute inset-0 flex items-center justify-center rounded-md text-muted-foreground opacity-0 transition-opacity group-hover:opacity-100 hover:text-foreground"
                  >
                    <X className="h-3 w-3" />
                  </button>
                </span>
              </button>
            )
          })}
      </div>
    </WidgetCard>
  )
})
